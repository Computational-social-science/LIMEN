#!/usr/bin/env python
"""build_item_bank.py -- deterministic item-bank builder for Phase I (O3), option C.

OPTION C, AS DIRECTED
    Expand the content space moderately (12 kernels per domain, each with >= 2 fillable slots) so the
    frozen size of 932 is reachable, and MEASURE the homogeneity that expansion creates rather than
    asserting it is harmless. The confound probe is `scripts/template_confound_probe.py`.

GOLD IS A CONSTRUCTION INVARIANT, NOT AN ANNOTATION
    Every item is rendered from a scenario kernel whose domain is known, so `intent_gold` cannot
    disagree with the item's construction and no labeler is involved. A human pass then checks only
    that an item is plausible and unambiguous to a reader -- never what the answer is. This removes the
    pilot's weakest feature (Amendment 1 section A4: gold assigned by the same agent that wrote the
    items, with no human pass).

AMBIGUITY IS A REJECTION, AND IT IS MECHANICAL
    An item generated for domain D is DROPPED if any rival domain's strong anchor appears in its text.
    The anchor sets are small and specific and exclude common co-occurring words (account, card,
    subscription) that would over-reject. `info` is the residual: an info item must contain no anchor.

PROVENANCE
    Templates are authored here. No earlier corpus is used, and nothing is generated by the pinned
    model -- the model is never the question-setter.

DETERMINISM
    Pure function of (size, seed). The dev/test split is by `item_id` hash, so an item sits in the same
    side at every lambda and every noise seed, which is what the within-item design rests on.

TEMPLATE ID
    Every item records `template_id` (domain + kernel index). This is what the confound probe groups
    on, and it is recorded at BUILD time so the probe cannot be accused of reconstructing it after
    seeing accuracy.
"""
