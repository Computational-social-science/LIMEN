CRITERIA = {
    "billing":  "a request about money: a charge, an invoice, a refund, or a payment method",
    "access":   "a request about getting in: sign-in, a password, a permission, or an account lock",
    "urgency":  "a request that needs immediate action because something is broken now or a deadline "
                "is close",
    "info":     "a request that only asks for information and needs no change to an account",
}


def anchors_of(text: str) -> set:
    t = text.lower()
    out = set()
    for dom, phrases in ANCHORS.items():
        for p in phrases:
            if p in t:
                out.add(dom)
                break
    return out


def is_unambiguous(domain: str, text: str) -> bool:
    return not (anchors_of(text) - {domain})


def build(size: int, seed: int, criteria_mode: str):
    rng = random.Random(seed)
    per = size // len(DOMAINS)
    rem = size - per * len(DOMAINS)
    quota = {d: per + (1 if i < rem else 0) for i, d in enumerate(DOMAINS)}

    n_opts_cycle = (2, 3, 4)
    items, rejected, seen = [], 0, set()
    counters = {d: 0 for d in DOMAINS}

    for domain in DOMAINS:
        kernels = KERNELS[domain]
        attempts, limit = 0, quota[domain] * 600
        while counters[domain] < quota[domain]:
            attempts += 1
            if attempts > limit:
                print(f"    [warn] {domain}: exhausted at {counters[domain]}/{quota[domain]} "
                      f"after {attempts} attempts", file=sys.stderr)
                break
            k_idx = rng.randrange(len(kernels))
            text = kernels[k_idx]
            for _ in range(3):
                text = re.sub(r"\{(\w+)\}", lambda m: rng.choice(SLOTS[m.group(1)]), text)
            if "{" in text:
                continue
            text = " ".join(text.split())
            if not is_unambiguous(domain, text):
                rejected += 1
                continue
            norm = re.sub(r"[^a-z ]", "", text.lower()).strip()
            if norm in seen:
                continue
            seen.add(norm)

            idx = counters[domain]
            counters[domain] += 1
            item_id = f"ph1_{domain}_{idx:04d}"
            n_opt = n_opts_cycle[idx % len(n_opts_cycle)]

            others = [d for d in DOMAINS if d != domain]
            local = random.Random(int(hashlib.sha256(item_id.encode()).hexdigest()[:8], 16))
            options = local.sample(others, n_opt - 1) + [domain]
            local.shuffle(options)

            intent = {"type": "choice",
                      "instructions": "Which category should this request be routed to?",
                      "options": options}
            if criteria_mode == "full":
                intent["criteria"] = {d: CRITERIA[d] for d in options}
            elif criteria_mode != "names":
                raise SystemExit(f"unknown criteria_mode: {criteria_mode}")

            items.append({
                "item_id": item_id,
                "state": text,
                "domain": domain,
                # recorded at BUILD time so the probe cannot reconstruct it after seeing accuracy
                "template_id": f"{domain}:k{k_idx:02d}",
                "intent": intent,
                "intent_gold": domain,
            })

    for it in items:
        h = int(hashlib.sha256(it["item_id"].encode()).hexdigest()[:8], 16)
        it["split"] = "dev" if (h % 100) < 30 else "test"
    return items, rejected


def main() -> int:
    ap = argparse.ArgumentParser(description="Build the Phase I item bank (O3, option C).")
    ap.add_argument("--size", type=int, default=932)
    ap.add_argument("--seed", type=int, default=20261004)
    ap.add_argument("--criteria-mode", choices=("full", "names"), default="full")
    ap.add_argument("--out", default="measurement/item_bank.jsonl")
    ap.add_argument("--manifest", default="measurement/item_bank_manifest.json")
    args = ap.parse_args()

    items, rejected = build(args.size, args.seed, args.criteria_mode)

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        for it in items:
            fh.write(json.dumps(it, ensure_ascii=False) + "\n")

    by_dom = collections.Counter(i["domain"] for i in items)
    by_split = collections.Counter(i["split"] for i in items)
    by_opts = collections.Counter(len(i["intent"]["options"]) for i in items)
    by_tpl = collections.Counter(i["template_id"] for i in items)
    by_dom_opts = collections.Counter((i["domain"], len(i["intent"]["options"])) for i in items)

    manifest = {
        "bank": str(out).replace("\\", "/"),
        "bank_sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
        "size": len(items),
        "requested_size": args.size,
        "seed": args.seed,
        "criteria_mode": args.criteria_mode,
        "ok_escalate": "DROPPED (Amendment 2 section B4: the noul primitive measured at chance in C2)",
        "gold_provenance": "CONSTRUCTION INVARIANT - not annotation. Each item is rendered from a "
                           "scenario kernel whose domain is known; no labeler is involved.",
        "ambiguity_rule": "an item for domain D is DROPPED if any rival domain's strong anchor appears "
                          "in its text. info is the residual and must contain no anchor.",
        "anchors_rejected_items": rejected,
        "template_id_recorded_at": "BUILD TIME, before any model scored the bank",
        "counts": {
            "per_domain": dict(by_dom),
            "per_split": dict(by_split),
            "per_option_count": dict(by_opts),
            "per_template": dict(by_tpl),
            "per_domain_x_options": {f"{d}|{n}": c for (d, n), c in sorted(by_dom_opts.items())},
        },
        "templates_per_domain": {d: len(KERNELS[d]) for d in DOMAINS},
        "items_per_template_min": min(by_tpl.values()),
        "items_per_template_max": max(by_tpl.values()),
        "chance_accuracy_by_option_count": {n: 1.0 / n for n in by_opts},
        "provenance": "templates authored in scripts/build_item_bank.py. No earlier corpus. "
                      "Not generated by the pinned model.",
    }
    mp = pathlib.Path(args.manifest)
    mp.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")

    print(f"  bank     -> {out}  ({len(items)} items, {out.stat().st_size} B)")
    print(f"  sha256   -> {manifest['bank_sha256']}")
    print(f"  manifest -> {mp}  ({mp.stat().st_size} B)")
    print()
    print(f"  per domain      : {dict(by_dom)}")
    print(f"  per split       : {dict(by_split)}   (30% dev / 70% test)")
    print(f"  per option count: {dict(by_opts)}")
    print(f"  templates/domain: {manifest['templates_per_domain']}")
    print(f"  items/template  : min {manifest['items_per_template_min']} max "
          f"{manifest['items_per_template_max']}  across {len(by_tpl)} templates")
    print(f"  rejected (mechanical ambiguity rule): {rejected}")
    print()
    if len(items) < args.size:
        print(f"  未达标: 目标 {args.size}, 实得 {len(items)}, 缺口 {args.size - len(items)}")
    else:
        print(f"  达标: {len(items)}/{args.size}")
    return 0


