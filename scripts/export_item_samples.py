"""Export an inspectable sample of RRC items for the report's item browser.

WHY A SAMPLE, AND WHY THIS KIND OF SAMPLE. The corpus holds 100,838 items and the report is a single
HTML file opened from disk, so the whole corpus cannot travel inside it. A uniform random draw would
be worse than useless here: `rrc-en-word` alone is 83 % of the corpus, so a random sample would show
an English word-level browser and almost nothing else -- and the per-cell structure, i.e. which layers
a given script even offers, is exactly what a reader needs to see.

So this is a SYSTEMATIC SAMPLE WITHIN EACH (arm, layer) CELL: sort each cell by item_id and take every
k-th item. It is deterministic, reproducible from the corpus alone, and it guarantees every cell is
represented -- including the 302-item Russian arm, which no proportional scheme would surface.

THE SELECTION IS NOT REPRESENTATIVE, AND THE PAYLOAD SAYS SO. Each exported item carries only the
fields the browser renders, and the payload carries the true per-arm totals so the page can print the
sampling ratio beside the sample instead of letting the sample stand in for the corpus.

    python scripts/export_item_samples.py            # write the sample
    python scripts/export_item_samples.py --check    # verify it is current
"""

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO / "data" / "rrc"
OUT = REPO / "viz" / "report" / "samples.js"

PER_CELL = 6          # items per (arm, layer) cell
MAX_PER_CELL_BYTES = 4000   # guard against a cell holding very long items

#  Fields that are constant within an arm are hoisted to the arm record, so they are not repeated in
#  every item. This is the difference between a 60 KB payload and a 200 KB one.
ARM_CONST = ("script_type", "script", "language")


def sample_cell(items):
    """Every k-th item of the cell, sorted by item_id. Deterministic and spread across the cell."""
    items = sorted(items, key=lambda d: d.get("item_id", ""))
    n = len(items)
    if n <= PER_CELL:
        return items
    step = n / PER_CELL
    return [items[int(i * step)] for i in range(PER_CELL)]


def slim(it):
    """Only the fields the browser renders. An unused field is payload the reader still downloads."""
    d = it.get("difficulty") or {}
    pr = it.get("provenance") or {}
    return {
        "id": it.get("item_id"),
        "l": it.get("layer"),
        "s": it.get("state"),
        "c": it.get("candidates") or [],
        "r": it.get("root"),
        "m": d.get("margin"),
        "gr": d.get("group_rank"),
        "gs": d.get("group_size"),
        "pk": pr.get("kind"),
        "pc": pr.get("corpus"),
        "pr": pr.get("source_record"),
    }


def build():
    arms = {}
    order = []
    for f in sorted(SRC.glob("*.jsonl")):
        arm = f.stem
        cells = {}
        total = 0
        const = {}
        for line in f.open(encoding="utf-8"):
            line = line.strip()
            if not line:
                continue
            it = json.loads(line)
            total += 1
            layer = it.get("layer") or "(none)"
            cells.setdefault(layer, []).append(it)
            for k in ARM_CONST:
                if k not in const and it.get(k):
                    const[k] = it[k]
        picked = []
        cell_counts = {}
        for layer in sorted(cells):
            sel = sample_cell(cells[layer])
            cell_counts[layer] = {"total": len(cells[layer]), "shown": len(sel)}
            picked.extend(slim(x) for x in sel)
        #  A cell whose items are unusually long is capped so one arm cannot dominate the payload.
        blob = json.dumps(picked, ensure_ascii=False)
        if len(blob) > MAX_PER_CELL_BYTES * max(1, len(cell_counts)):
            picked = picked[: max(1, len(cell_counts)) * 4]
        arms[arm] = {
            "totals": {"items": total, "cells": cell_counts},
            "const": const,
            "items": picked,
        }
        order.append(arm)

    return {
        "note": ("A systematic sample within each (arm, layer) cell -- every k-th item by item_id, "
                 "not a uniform random draw and not proportional to the corpus. Cells with fewer "
                 "items than the per-cell quota are shown whole. Compare 'shown' against 'total' in "
                 "each arm's cells: the sample is for inspection, the totals are the corpus."),
        "per_cell": PER_CELL,
        "arm_order": order,
        "arms": arms,
    }


def main():
    payload = build()
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    #  `</script>` inside a JS string would close the host tag if this file were ever inlined.
    body = body.replace("<", "\\u003c")
    js = ("//  Generated by scripts/export_item_samples.py -- do not edit by hand.\n"
          "//  An inspectable sample of the corpus, drawn systematically within each (arm, layer)\n"
          "//  cell. It is NOT a random sample and NOT proportional: see payload.note.\n"
          "window.RRC_SAMPLES = " + body + ";\n")

    if "--check" in sys.argv:
        if not OUT.exists():
            print("  [FAIL] %s does not exist" % OUT); return 1
        cur = OUT.read_text(encoding="utf-8")
        if cur.strip() == js.strip():
            n = sum(len(a["items"]) for a in payload["arms"].values())
            print("  [OK] samples.js is current: %d items across %d arms" % (n, len(payload["arms"])))
            return 0
        print("  [FAIL] samples.js is stale against the corpus -- re-run without --check"); return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(js, encoding="utf-8")
    shown = sum(len(a["items"]) for a in payload["arms"].values())
    tot = sum(a["totals"]["items"] for a in payload["arms"].values())
    print("  wrote %s" % OUT)
    print("  %d of %d items shown (%.2f %%), %d arms" % (shown, tot, 100 * shown / max(1, tot),
                                                         len(payload["arms"])))
    for a in payload["arm_order"]:
        cells = payload["arms"][a]["totals"]["cells"]
        print("    %-14s %6d items  cells: %s" %
              (a, payload["arms"][a]["totals"]["items"],
               "  ".join("%s=%d/%d" % (l, v["shown"], v["total"]) for l, v in sorted(cells.items()))))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
