STATUS_MARK = {"PROVED": "**PROVED**", "ASSUMED": "*ASSUMED*", "TESTED": "**TO BE TESTED**"}


def verified_theorems() -> set[str]:
    """Names the kernel actually checked. Source of truth is the Lean file plus a clean axiom run."""
    src = (LEAN_ROOT / "NHB" / "PhaseI" / "Core.lean").read_text(encoding="utf-8")
    names = set(re.findall(r"^theorem\s+(\w+)", src, re.M))
    proc = subprocess.run([sys.executable, "-B", str(REPO_ROOT / "scripts" / "check_lean_axioms.py")],
                          capture_output=True, text=True, cwd=REPO_ROOT, timeout=600)
    m = re.search(r"OK: (\d+) theorem\(s\)", proc.stdout)
    if proc.returncode != 0 or not m:
        raise SystemExit("the kernel axiom check did not pass - refusing to publish a provenance "
                         "table over an unverified formalisation\n" + (proc.stdout + proc.stderr)[:600])
    checked = int(m.group(1))
    if checked != len(names):
        raise SystemExit(f"the kernel checked {checked} theorems but the source declares {len(names)}; "
                         "resolve that before publishing the table")
    return names


def build_table(theorems: set[str]) -> str:
    missing: list[str] = []
    for claim, status, authority, _ in CLAIMS:
        if status != "PROVED":
            continue
        for name in [a.strip() for a in authority.split(",")]:
            if name not in theorems:
                missing.append(f"{claim!r} cites {name!r}, which is not a verified theorem")
    if missing:
        print("FAIL: a claim is marked PROVED against a theorem that does not exist.")
        for m in missing:
            print("  -", m)
        print("\nA proof that was never done is the one thing this table must not contain.")
        sys.exit(1)

    lines = [
        BEGIN,
        "",
        "### 12.1 Claim provenance — what is proved, what is assumed, what is tested",
        "",
        f"Generated by `scripts/build_provenance_table.py` from the kernel-verified set of "
        f"**{len(theorems)} theorems**. A row marked **PROVED** names a theorem the kernel checked; the "
        f"generator fails if such a theorem does not exist, so this table cannot claim a proof that was "
        f"never done. **No row here is marked PROVED for a statement that noise changes Accuracy, "
        f"SilentError or Coverage** — those are the empirical claims, and no theorem can settle them.",
        "",
        "| Claim as the protocol states it | Status | Authority | Note |",
        "|---|---|---|---|",
    ]
    for claim, status, authority, note in CLAIMS:
        auth = f"`{authority}`" if status == "PROVED" else authority
        lines.append(f"| {claim} | {STATUS_MARK[status]} | {auth} | {note} |")
    counts = {s: sum(1 for _, st, _, _ in CLAIMS if st == s) for s in ("PROVED", "ASSUMED", "TESTED")}
    lines += [
        "",
        f"**{counts['PROVED']} proved · {counts['ASSUMED']} assumed · {counts['TESTED']} to be tested.** "
        f"The third column is the whole point: a reader can see which conclusions rest on the kernel, "
        f"which on a premise the design chose, and which on the run that has not happened yet.",
        "",
        END,
    ]
    return "\n".join(lines)


def negative_test() -> int:
    """Inject a claim that is PROVED against a theorem that does not exist, and require a failure.

    A generator that only ever succeeds is not a check. This control asserts the property the table
    exists for: a claimed proof that was never done must stop the build. The injected name is real-looking
    on purpose - a typo of an actual theorem is the shape this defect would take in practice.
    """
    global CLAIMS
    original = CLAIMS
    try:
        CLAIMS = original + [("(negative control) an invented claim", "PROVED",
                              "risk_mono_but_actually_does_not_exist", "injected")]
        try:
            build_table(verified_theorems())
        except SystemExit as exc:
            if exc.code == 1:
                print("  negative control: the generator refused an unproved claim  OK")
                return 0
            print(f"  negative control: exited {exc.code} rather than 1")
            return 1
        print("  negative control FAILED: an unproved claim was accepted into the table")
        return 1
    finally:
        CLAIMS = original


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="verify the protocol's table matches the derived truth; write nothing")
    ap.add_argument("--negative-test", action="store_true",
                    help="inject an unproved claim and require the generator to refuse it")
    args = ap.parse_args()

    if args.negative_test:
        return negative_test()

    text = PROTOCOL.read_text(encoding="utf-8")
    new_block = build_table(verified_theorems())

    if BEGIN not in text or END not in text:
        if args.check:
            print("FAIL: the protocol has no provenance block to check.")
            return 1
        anchor = "## 13."
        i = text.find(anchor)
        if i < 0:
            raise SystemExit("cannot find the insertion anchor ('## 13.') in the protocol")
        text = text[:i] + new_block + "\n\n---\n\n" + text[i:]
        PROTOCOL.write_text(text, encoding="utf-8", newline="\n")
        print("  provenance table inserted into the protocol")
        return 0

    i = text.find(BEGIN)
    j = text.find(END, i) + len(END)
    current = text[i:j]
    if current == new_block:
        print(f"  OK: provenance table is current "
              f"({len(CLAIMS)} claims, all PROVED rows name verified theorems)")
        return 0
    if args.check:
        print("FAIL: the provenance table in the protocol does not match the derived truth.")
        cur_lines, new_lines = current.splitlines(), new_block.splitlines()
        for k in range(max(len(cur_lines), len(new_lines))):
            a = cur_lines[k] if k < len(cur_lines) else "<absent>"
            b = new_lines[k] if k < len(new_lines) else "<absent>"
            if a != b:
                print(f"  first difference at line {k + 1}:\n    in protocol: {a[:110]}\n    derived    : {b[:110]}")
                break
        return 1

    text = text[:i] + new_block + text[j:]
    PROTOCOL.write_text(text, encoding="utf-8", newline="\n")
    print("  provenance table refreshed in the protocol")
    return 0


if __name__ == "__main__":
    sys.exit(main())