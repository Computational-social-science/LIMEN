#!/usr/bin/env python
"""build_provenance_table.py -- derive a claim-by-claim provenance table and write it into the protocol.

WHY THIS EXISTS
    The protocol now contains four kinds of statement, and until this table existed a reader could not
    tell them apart: (i) facts the kernel proved, (ii) premises the design takes as given, (iii) empirical
    claims the run will test, and (iv) claims that are none of those but read as though they were. A
    formalisation that is cited in the prose but not mapped to the claims makes the whole document look
    machine-checked, which is worse than not having it. This table is the map.

THE RULE THAT MAKES IT MORE THAN DOCUMENTATION
    A row marked PROVED must name a theorem that actually exists in the kernel-verified set. If it does
    not, this script FAILS rather than writing the row. So the table cannot drift into claiming proofs
    that were never done - the failure mode the project has already hit once, when a status record
    overstated a theorem count and nothing but a hand-written guard noticed.

WHAT NO ROW MAY SAY
    No row is marked PROVED if what it asserts is that noise changes Accuracy, SilentError or Coverage.
    Those are the empirical claims, and by construction no theorem can prove them: they are stated as a
    named premise in §4.4 and tested by the run. `check` mode enforces that no such row appears as PROVED,
    because "the formalisation proves the hypothesis" is the one misreading this table exists to prevent.
"""

