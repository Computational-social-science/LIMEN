def parse_core() -> list[dict]:
    """Return [{name, statement, section}] in source order."""
    text = CORE.read_text(encoding="utf-8")
    sections = [(m.start(), re.sub(r"\s+", " ", m.group(1)).strip())
                for m in re.finditer(r"/-!\s*#+\s*(.*?)\s*-/", text, re.S)]
    out = []
    for m in re.finditer(r"^theorem\s+(\w+)", text, re.M):
        name, after = m.group(1), m.end()
        i, depth = after, 0
        stmt = ""
        while i < len(text) - 1:
            ch = text[i]
            if ch in "([{":
                depth += 1
            elif ch in ")]}":
                depth -= 1
            elif ch == ":" and text[i:i + 2] == ":=" and depth == 0:
                stmt = " ".join(text[after:i].split())
                break
            i += 1
        if not stmt:
            raise SystemExit(f"could not find the proof opening for `{name}`; refusing to publish a "
                             f"truncated statement in a proof appendix")
        section = next((nm for pos, nm in reversed(sections) if pos < m.start()), "")
        out.append({"name": name, "statement": stmt, "section": section})
    return out


def build() -> str:
    thms = parse_core()
    names = {t["name"] for t in thms}

    undeclared = sorted(names - set(BEARS_ON))
    phantom = sorted(set(BEARS_ON) - names)
    problems = []
    if undeclared:
        problems.append("PROVED BUT UNDECLARED (a proof nobody decided the meaning of): "
                        + ", ".join(undeclared))
    if phantom:
        problems.append("DECLARED BUT ABSENT (the appendix would cite a proof that does not exist): "
                        + ", ".join(phantom))
    if problems:
        print("FAIL: the theorem-to-claim map is not a bijection.")
        for p in problems:
            print("  -", p)
        print("\nThe map is complete by construction or the build stops.")
        sys.exit(1)

    grouped: dict[str, list[dict]] = {}
    for t in thms:
        grouped.setdefault(t["section"], []).append(t)

    L = [
        BEGIN,
        "",
        "## 15. Machine-checked core",
        "",
        "**This section is generated from the Lean source, not transcribed from it.** Every statement below "
        "was extracted from the source by a bracket-depth scan and every theorem named here was verified by "
        "the kernel (`#print axioms`) to depend on no `sorry`. The generator fails the build if a theorem "
        "has no declared bearing below, or if a bearing cites a theorem that does not exist, so the table "
        "cannot quietly acquire a proof that was never done or lose one that was.",
        "",
        f"**{len(thms)} theorems, zero errors, zero `sorry`.** The permitted axioms are `propext`, "
        "`Quot.sound` and `Classical.choice` - the last being Lean's classical logic, not a gap in a proof.",
        "",
        "**How the check runs, and why it is trusted.** Three things had to hold before any of these "
        "statements could be used to correct the protocol: (1) the kernel query returns a `#print axioms` "
        "line for every theorem, and an empty answer *raises* rather than passing - because absent output "
        "reads exactly like \"axiom-free\"; (2) a negative control injects a `sorry`-proved theorem into "
        "the real file, rebuilds, and requires the check to catch it; (3) a freshness guard re-derives "
        "every theorem and line count from the source so a stale number in a document cannot survive. "
        "Without (2) and (3) the first check is a green light with nothing behind it.",
        "",
        "**The correction record in §4.4b was produced by this machinery, not confirmed by it.** Each of "
        "the seven entries there is a place where a machine-checked statement contradicted a sentence the "
        "protocol had already written - a direction, an optimality claim, a degeneracy, a domain of "
        "definition, a family's dependence structure, an endpoint's identifiability, and a reporting "
        "procedure. So the table below is the evidence for §4.4b, and §4.4b is the interpretation of it.",
        "",
    ]
    for section, items in grouped.items():
        title = SECTION_TITLES.get(section, section or "unnamed section")
        L += [f"**{title}**", "",
              "| Theorem | Statement | What it bears on | Section |", "|---|---|---|---|"]
        for t in items:
            bears, sec = BEARS_ON[t["name"]]
            stmt = t["statement"].replace("|", "\\|")
            if len(stmt) > 210:
                stmt = stmt[:207] + "…"
            L.append(f"| `{t['name']}` | `{stmt}` | {bears} | {sec} |")
        L.append("")
    L += [
        "**Authority:** `scripts/check_lean_axioms.py` (kernel query, with a negative control), "
        "`scripts/check_lean_status_freshness.py` (derived counts), "
        "`scripts/build_proof_appendix.py --check` (this section is current, and the map is a bijection).",
        "",
        END,
    ]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--check", action="store_true", help="verify the section in the protocol is current")
    ap.add_argument("--negative-test", action="store_true",
                    help="inject an undeclared theorem and require the bijection check to refuse it")
    args = ap.parse_args()

    if args.negative_test:
        global BEARS_ON
        saved = dict(BEARS_ON)
        try:
            BEARS_ON.pop("admissible_iff_limen_le", None)
            try:
                build()
            except SystemExit as exc:
                if exc.code == 1:
                    print("  negative control: an undeclared theorem was refused  OK")
                    return 0
                print(f"  negative control: exited {exc.code} rather than 1")
                return 1
            print("  negative control FAILED: a theorem with no declared bearing was accepted")
            return 1
        finally:
            BEARS_ON = saved

    text = PROTOCOL.read_text(encoding="utf-8")
    block = build()

    if BEGIN in text and END in text:
        i = text.find(BEGIN)
        j = text.find(END, i) + len(END)
        current = text[i:j]
        if current == block:
            print(f"  OK: proof appendix is current ({len(parse_core())} theorems, map is a bijection)")
            return 0
        if args.check:
            print("FAIL: the proof appendix in the protocol does not match the Lean source.")
            cur, new = current.splitlines(), block.splitlines()
            for k in range(max(len(cur), len(new))):
                a = cur[k] if k < len(cur) else "<absent>"
                b = new[k] if k < len(new) else "<absent>"
                if a != b:
                    print(f"  first difference at line {k + 1}:\n    in protocol: {a[:100]}\n"
                          f"    derived    : {b[:100]}")
                    break
            return 1
        text = text[:i] + block + text[j:]
        PROTOCOL.write_text(text, encoding="utf-8", newline="\n")
        print("  proof appendix refreshed in the protocol")
        return 0

    if args.check:
        print("FAIL: the protocol has no proof appendix to check.")
        return 1

    anchor = "*End of protocol v"
    k = text.rfind(anchor)
    if k < 0:
        raise SystemExit("cannot find the protocol's end marker to insert before")
    text = text[:k] + block + "\n\n---\n\n" + text[k:]
    PROTOCOL.write_text(text, encoding="utf-8", newline="\n")
    print(f"  proof appendix inserted ({len(parse_core())} theorems, map is a bijection)")
    return 0


if __name__ == "__main__":
    sys.exit(main())