"""build_proof_appendix.py -- derive a machine-checked core section and write it into the protocol.

WHY THIS EXISTS, AND WHY IT IS NOT §4.4b
    §4.4b records WHAT the machine check changed: seven corrections, each a place a proof contradicted a
    sentence the protocol had already written. §12.1 records which claim rests on which theorem. Neither
    shows the PROOF ITSELF - the statements that were checked, grouped as they are grouped in the source,
    and the procedure that checked them. A reader who wants to know whether a claim is load-bearing or
    decorative has to open the Lean file, which is exactly the position the provenance table exists to
    avoid.

    The HTML is the deliverable and also the first thing to iterate. So the proof process is iterated into
    it: theorem, statement, and what each one bears on, generated from the source rather than transcribed.

THE TWO CHECKS THAT MAKE THIS MORE THAN A LISTING
    1. The theorem-to-claim map must be a BIJECTION. A theorem with no declared bearing fails the build,
       because an undeclared theorem is a proof nobody has decided the meaning of; a declared theorem
       that does not exist also fails. Keeping the map complete is therefore not a matter of diligence.
    2. Every statement is extracted from the Lean source by a bracket-depth scan for the `:=` that opens
       the proof, not by a regex over lines. Theorems here span several lines and contain `:=` inside
       their own bodies (`AccDefersWrong : Nat -> List Obs -> Nat | _, [] => 0 | ...`), so a line-based
       pattern silently truncates or over-reads. A truncated statement in a proof appendix is worse than
       no appendix.

WHAT THIS FILE DOES NOT CLAIM
    It does not claim the statements are interesting, or that proving them was hard. It reports what the
    kernel accepted. Whether a theorem bears on the right question is a judgement, and it is recorded as
    a judgement in the `bears on` column, not derived.
"""

