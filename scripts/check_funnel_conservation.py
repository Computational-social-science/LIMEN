"""check_funnel_conservation.py -- the corpus's own accounting must close, without a rebuild.

WHY THIS EXISTS
    Drawing the construction funnel honestly required subtracting counts, and the subtraction did not
    work: rrc-en-word appeared to ship 84,001 items from 36,133 records. Two different units had been
    pooled -- a record is a pair read from a corpus, an item is one question, and a record yields up
    to three questions -- and underneath that, two loss stages were counted nowhere at all:

      * records that cleared both record-level gates and then produced no layer (largest single loss
        on rrc-ja);
      * items the source offers twice, discarded by the dedupe (found only when the first
        conservation assertion was written and immediately failed on rrc-en: 2,828 attempted, 2,447
        accounted for).

    Both are now counted, and the builder asserts the identities as it runs. This guard checks the
    same identities against the SHIPPED MANIFEST, so a manifest edited or regenerated by any other
    path is caught without waiting for a fifteen-minute rebuild. A funnel that does not close is
    worse than no funnel: it reads as a complete account of the losses while hiding at least one.

   THE IDENTITIES, per arm:
      record level   source_records == dropped + dropped_script + dropped_no_layer
                                      + records_with_layer
      item level     items_attempted == dropped_duplicate + dropped_margin + n_items
      layer tally    n_items == sum(layers.values())

NEGATIVE CONTROL
    `--negative-test` perturbs one arm's `dropped_no_layer` by +1 IN MEMORY and requires the check to
    report it. Nothing is written, so the control cannot leave a defect behind in the manifest.
"""
from __future__ import annotations

import copy
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = REPO / "config" / "rrc.json"


def violations(arms: dict) -> list[str]:
    """Every way an arm's accounting fails to close. Empty list means it closes."""
    out = []
    for arm, m in arms.items():
        g = lambda k: m.get(k) or 0  # noqa: E731
        rec_sum = (g("dropped_unit") + g("dropped") + g("dropped_script") + g("dropped_no_layer")
                   + g("records_with_layer"))
        if m.get("source_records") is None:
            out.append("%s: no source_records" % arm)
        elif rec_sum != m["source_records"]:
            out.append("%s: record level does not close -- %d != source_records %d (gap %+d)"
                       % (arm, rec_sum, m["source_records"], m["source_records"] - rec_sum))
        it_sum = g("dropped_duplicate") + g("dropped_margin") + g("n_items")
        if m.get("items_attempted") is None:
            out.append("%s: no items_attempted" % arm)
        elif it_sum != m["items_attempted"]:
            out.append("%s: item level does not close -- shipped+dup+margin = %d != attempted %d "
                       "(gap %+d)" % (arm, it_sum, m["items_attempted"],
                                      m["items_attempted"] - it_sum))
        if m.get("n_items") is not None and m.get("per_layer"):
            lay = sum(m["per_layer"].values())
            if lay != m["n_items"]:
                out.append("%s: layer tally %d != n_items %d" % (arm, lay, m["n_items"]))
    return out


def main() -> int:
    if not MANIFEST.exists():
        # The manifest describes the RRC corpus, which was RETIRED on 2026-10-11 as
        # an invalid measurement instrument (0 of its 17 (arm, layer) cells usable;
        # see CURRENT_OBJECT.md R3 and archive/rrc-v2.0.0-INVALID/WHY_RETIRED.md).
        # `data/rrc` is listed under RETIRED_ARTIFACTS in check_object_drift.py.
        #
        # So the subject of this guard no longer exists, and the honest report is
        # INAPPLICABLE -- not FAIL. A guard that goes red because its subject was
        # deliberately retired is testing the wrong thing, and a permanently red
        # suite is indistinguishable from a broken one: it makes the pre-commit hook
        # unusable and teaches everyone to bypass it. This is the same convention
        # check_handoff_freshness.py uses for the deprecated handoff note.
        #
        # The guard is NOT deleted. It becomes live again the moment a replacement
        # corpus ships a manifest at this path, which is the standing requirement
        # any replacement must satisfy (docs/POSTMORTEM_RRC_VALIDITY.md).
        print("  [SKIP] INAPPLICABLE: no manifest at %s" % MANIFEST)
        print("         the RRC corpus was retired 2026-10-11 (CURRENT_OBJECT.md R3), so there is")
        print("         no funnel to conserve. This guard re-arms automatically if a replacement")
        print("         corpus ships config/rrc.json. It proves NOTHING until then.")
        return 0
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))
    arms = man.get("arms") or {}
    if not arms:
        print("  [FAIL] the manifest carries no arms block")
        return 1

    if "--negative-test" in sys.argv:
        bad = copy.deepcopy(arms)
        first = sorted(bad)[0]
        bad[first]["dropped_no_layer"] = (bad[first].get("dropped_no_layer") or 0) + 1
        found = violations(bad)
        if any(first in v and "record level" in v for v in found):
            print("  [OK] negative control fires: %s" % found[0])
            return 0
        print("  [FAIL] the injected record-level gap was NOT reported: %s" % (found or "none"))
        return 1

    found = violations(arms)
    tot_rec = sum(m.get("source_records") or 0 for m in arms.values())
    tot_item = sum(m.get("items_attempted") or 0 for m in arms.values())
    tot_ship = sum(m.get("n_items") or 0 for m in arms.values())
    print("  %d arm(s); %s records read, %s questions attempted, %s shipped"
          % (len(arms), format(tot_rec, ","), format(tot_item, ","), format(tot_ship, ",")))
    if found:
        print()
        for v in found:
            print("  [FAIL] %s" % v)
        print()
        print("  A stage is missing from the accounting, or two are being added together.")
        return 1
    print("  [OK] both stages close on every arm (%d identities per arm checked twice)"
          % len(arms))
    return 0


if __name__ == "__main__":
    sys.exit(main())
