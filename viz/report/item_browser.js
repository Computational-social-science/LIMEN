//  RRC item browser -- the corpus itself, one item at a time.
//
//  WHY THIS VIEW. The other views show aggregates: how many items each gate removed, which layers an
//  arm offers, what the distributions look like. A reader can study all of that and still not know
//  what an ITEM is. This view answers that by showing the task as the instrument receives it: an
//  observed corrupted form and five candidates, exactly one of which is its root.
//
//  IT LETS THE READER ANSWER. The correct candidate is not marked until the reader commits to one.
//  Marking it in advance would turn a measurement into a quiz with the answer printed on it; the
//  reader learns nothing about the task's difficulty. After the choice is made the view reports what
//  the item's recorded difficulty is, so the reader can compare their own difficulty against it.
//
//  DATA CONTRACT. Everything comes from `window.RRC_SAMPLES` (generated by
//  scripts/export_item_samples.py). That is a SYSTEMATIC SAMPLE within each (arm, layer) cell, not a
//  random draw and not proportional -- `rrc-en-word` is 83 % of the corpus and would swamp any
//  proportional view. The sampling note travels in the payload and is printed here, and the true
//  totals sit beside it, so the sample is never mistaken for the corpus.
//
//  All corpus text is written with textContent. Nothing from the corpus is ever parsed as markup:
//  these strings come from human error corpora and may contain anything.

(function () {
  "use strict";

  var RB = window.RRC_SAMPLES;
  var HOSTS = ["ib-tabs", "ib-layers", "ib-stage", "ib-note"];

  function bail(msg) {
    HOSTS.forEach(function (id) {
      var h = document.getElementById(id);
      if (!h) return;
      h.innerHTML = "";
      var d = document.createElement("div");
      d.className = "dx-error";
      d.textContent = msg;
      h.appendChild(d);
    });
    var s = document.getElementById("ib-stage");
    if (s) s.setAttribute("data-ib-error", msg);
  }

  if (!RB || !RB.arms || !RB.arm_order || !RB.arm_order.length) {
    bail("The item sample did not load, so nothing can be shown. This view stays empty rather " +
         "than displaying invented items.");
    return;
  }

  var ARMS = RB.arm_order;
  var cur = { arm: ARMS[0], layer: null, idx: 0, revealed: false, picked: null };

  function layersOf(a) {
    var cells = (RB.arms[a] && RB.arms[a].totals && RB.arms[a].totals.cells) || {};
    return Object.keys(cells).sort();
  }
  function itemsOf() {
    var all = (RB.arms[cur.arm] && RB.arms[cur.arm].items) || [];
    return cur.layer ? all.filter(function (x) { return x.l === cur.layer; }) : all;
  }

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text !== undefined && text !== null) e.textContent = String(text);
    return e;
  }

  // ── selectors ──────────────────────────────────────────────────────────────────────────────────
  //  The arm tabs and layer chips carry their own counts, so the reader can see that the language
  //  arms are small and the English word-level arm is most of the corpus. That proportion is itself
  //  a property of the dataset and hiding it would misrepresent the sample's basis.

  function drawTabs() {
    var host = document.getElementById("ib-tabs");
    if (!host) return;
    host.innerHTML = "";
    ARMS.forEach(function (a) {
      var b = el("button", "dx-tab", a + "  " + (RB.arms[a].totals.items).toLocaleString("en-US"));
      b.type = "button";
      if (a === cur.arm) b.className += " is-active";
      b.addEventListener("click", function () {
        cur.arm = a; cur.layer = null; cur.idx = 0; cur.revealed = false; cur.picked = null;
        drawTabs(); drawLayers(); drawItem();
      });
      host.appendChild(b);
    });
  }

  function drawLayers() {
    var host = document.getElementById("ib-layers");
    if (!host) return;
    host.innerHTML = "";
    var ls = layersOf(cur.arm);
    var cells = RB.arms[cur.arm].totals.cells;
    var all = el("button", "dx-tab" + (cur.layer === null ? " is-active" : ""),
                 "all layers");
    all.type = "button";
    all.addEventListener("click", function () {
      cur.layer = null; cur.idx = 0; cur.revealed = false; cur.picked = null; drawLayers(); drawItem();
    });
    host.appendChild(all);
    ls.forEach(function (l) {
      var c = cells[l] || {};
      var b = el("button", "dx-tab" + (cur.layer === l ? " is-active" : ""),
                 l + "  " + c.shown + "/" + c.total);
      b.type = "button";
      b.addEventListener("click", function () {
        cur.layer = l; cur.idx = 0; cur.revealed = false; cur.picked = null; drawLayers(); drawItem();
      });
      host.appendChild(b);
    });
  }

  // ── the item ───────────────────────────────────────────────────────────────────────────────────

  function drawItem() {
    var host = document.getElementById("ib-stage");
    if (!host) return;
    var items = itemsOf();
    host.innerHTML = "";
    host.removeAttribute("data-ib-marks");

    if (!items.length) {
      host.appendChild(el("div", "dx-error", "No item in this cell."));
      return;
    }
    if (cur.idx >= items.length) cur.idx = 0;
    var it = items[cur.idx];

    var head = el("div", "ib-head");
    head.appendChild(el("span", "ib-id", it.id));
    head.appendChild(el("span", "ib-tag", it.l || "\u2014"));
    if (it.pk) {
      var prov = it.pc ? (it.pk + " \u00b7 " + it.pc) : it.pk;
      var t = el("span", "ib-tag ib-prov", prov);
      if (it.pr) t.title = "source record: " + it.pr;
      head.appendChild(t);
    }
    host.appendChild(head);

    host.appendChild(el("p", "ib-ask",
      "The form below is an observed corrupted form. Which candidate is its root?"));

    var form = el("div", "ib-state");
    form.appendChild(el("span", "ib-state-lab", "observed"));
    form.appendChild(el("span", "ib-state-val", it.s));
    host.appendChild(form);

    var grid = el("div", "ib-cands");
    var marks = 0;
    (it.c || []).forEach(function (cand, i) {
      var b = el("button", "ib-cand");
      b.type = "button";
      var letter = el("span", "ib-letter", String.fromCharCode(65 + i));
      var word = el("span", "ib-word", cand);
      b.appendChild(letter); b.appendChild(word);
      if (cur.revealed) {
        b.disabled = true;
        if (cand === it.r) b.className += " is-root";
        else if (cand === cur.picked) b.className += " is-wrong";
      }
      b.addEventListener("click", function () {
        if (cur.revealed) return;
        cur.picked = cand;
        cur.revealed = true;
        drawItem();
      });
      grid.appendChild(b);
      marks++;
    });
    grid.setAttribute("data-ib-marks", String(marks));
    host.appendChild(grid);

    if (cur.revealed) {
      var rev = el("div", "ib-reveal");
      rev.appendChild(el("span", "ib-root", "root: " + (it.r === null ? "\u2014" : it.r)));
      var d = [];
      if (it.m !== null && it.m !== undefined) d.push("margin " + it.m);
      else d.push("margin not defined for this layer");
      if (it.gr !== null && it.gr !== undefined) d.push("group rank " + it.gr);
      if (it.gs !== null && it.gs !== undefined) d.push("group size " + it.gs);
      rev.appendChild(el("span", "ib-diff", d.join("  \u00b7  ")));
      host.appendChild(rev);
    }

    var nav = el("div", "ib-nav");
    var prev = el("button", "dx-tab", "\u2190 previous");
    prev.type = "button";
    prev.disabled = cur.idx === 0;
    prev.addEventListener("click", function () {
      cur.idx = Math.max(0, cur.idx - 1); cur.revealed = false; cur.picked = null; drawItem();
    });
    var pos = el("span", "ib-pos", (cur.idx + 1) + " / " + items.length +
                 (cur.layer ? "  in " + cur.layer : "  in " + cur.arm));
    var next = el("button", "dx-tab", "next \u2192");
    next.type = "button";
    next.disabled = cur.idx >= items.length - 1;
    next.addEventListener("click", function () {
      cur.idx = Math.min(items.length - 1, cur.idx + 1); cur.revealed = false; cur.picked = null; drawItem();
    });
    nav.appendChild(prev); nav.appendChild(pos); nav.appendChild(next);
    host.appendChild(nav);

    host.setAttribute("data-ib-items", String(items.length));
  }

  function drawNote() {
    var host = document.getElementById("ib-note");
    if (!host) return;
    host.innerHTML = "";
    host.appendChild(el("p", "dx-cap", RB.note || ""));
    var tot = 0, shown = 0;
    ARMS.forEach(function (a) {
      tot += RB.arms[a].totals.items;
      shown += RB.arms[a].items.length;
    });
    host.appendChild(el("p", "ib-count",
      shown.toLocaleString("en-US") + " items shown of " + tot.toLocaleString("en-US") +
      " in the corpus (" + (100 * shown / tot).toFixed(2) + " %) \u00b7 " +
      RB.per_cell + " per (arm, layer) cell"));
  }

  drawTabs();
  drawLayers();
  drawItem();
  drawNote();
})();
