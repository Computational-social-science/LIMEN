//  RRC dataset explorer -- the dataset's paradigm, drawn from the exported state.
//
//  WHY THIS EXISTS. The static figures show the RESULTS: accuracy by rank, the displacement, the
//  measured channel. They do not show the DATASET -- where its items came from, what the gates
//  removed, and which layers are even comparable across scripts. That structure is a directed graph
//  with counts on every edge, and a reader reconstructs it from prose or not at all. These three
//  linked views make it direct: the funnel arm by arm, the layer coverage matrix, and the
//  distributional signature each arm carries.
//
//  DATA CONTRACT. Everything comes from `window.APP_STATE` (loaded by state.js, which is generated by
//  scripts/export_report_state.py). There is NO fetch and NO embedded copy: this page must work from
//  file:// where XHR is blocked, and a second copy of the numbers would be a second source of truth.
//  If the state is absent every view says so and draws nothing -- an empty frame is a defect, a
//  fabricated frame is a lie.
//
//  Every rendered group carries `data-d3-marks` with its mark count so a render-time guard can assert
//  the drawing happened. A canvas that silently draws nothing is the failure mode this guards.

(function () {
  "use strict";

  var S = window.APP_STATE;
  var NS = "http://www.w3.org/2000/svg";

  //  The report's own palette, so the interactive views sit inside the document rather than beside it.
  var C = {
    ink: "#12161c", dim: "#5a6472", line: "#d8dee7", panel: "#f7f8fa",
    keep: "#1b3a6b", drop: "#b04a3a", soft: "#476b9d", warn: "#8a5a00", ok: "#1d6b3a"
  };

  function fail(host, msg) {
    host.innerHTML = "";
    var d = document.createElement("div");
    d.className = "dx-error";
    d.textContent = msg;
    host.appendChild(d);
    host.setAttribute("data-d3-error", msg);
  }

  if (!S || !S.arms) {
    ["dx-funnel", "dx-layers", "dx-stats"].forEach(function (id) {
      var h = document.getElementById(id);
      if (h) fail(h, "The report state did not load, so this view cannot draw. Nothing is shown " +
                     "rather than something invented.");
    });
    return;
  }

  var ARM_ORDER = (S.arm_order || Object.keys(S.arms)).filter(function (a) { return S.arms[a]; });
  var LAYER_ORDER = ["L1", "L2c", "L2k", "L3", "L4"];

  // ── tooltip ────────────────────────────────────────────────────────────────────────────────────
  var tip = document.createElement("div");
  tip.className = "dx-tip";
  document.body.appendChild(tip);
  function showTip(ev, html) {
    tip.innerHTML = html;
    tip.style.opacity = "1";
    var pad = 14, w = tip.offsetWidth, h = tip.offsetHeight;
    var x = ev.clientX + pad, y = ev.clientY + pad;
    if (x + w > window.innerWidth - 8) x = ev.clientX - w - pad;
    if (y + h > window.innerHeight - 8) y = ev.clientY - h - pad;
    tip.style.left = x + "px";
    tip.style.top = y + "px";
  }
  function hideTip() { tip.style.opacity = "0"; }
  function fmt(n) { return (n === null || n === undefined) ? "\u2014" : n.toLocaleString("en-US"); }

  // ── A. the funnel, arm by arm ──────────────────────────────────────────────────────────────────
  //  Each arm is a chain of five gates. Drawn as a stage chart: bar length is the count surviving
  //  that stage, so the reader sees WHERE the loss happens, not just how much. The gates are ordered
  //  as the builder applies them.

  function stagesOf(a) {
    var st = [
      { k: "source_records",     label: "source records",        kind: "src",  n: a.source_records },
      { k: "dropped_script",     label: "gate: script purity",   kind: "drop", n: a.dropped_script },
      { k: "dropped_duplicate",  label: "gate: duplicate",       kind: "drop", n: a.dropped_duplicate },
      { k: "dropped_unit",       label: "gate: unit consistency", kind: "drop", n: a.dropped_unit },
      { k: "dropped_margin",     label: "gate: margin",          kind: "drop", n: a.dropped_margin },
      { k: "dropped_no_layer",   label: "gate: no layer",        kind: "drop", n: a.dropped_no_layer },
      { k: "records_with_layer", label: "records with a layer",  kind: "keep", n: a.records_with_layer },
      { k: "items_attempted",    label: "items assembled",       kind: "keep", n: a.items_attempted }
    ];
    return st.filter(function (s) { return typeof s.n === "number"; });
  }

  function drawFunnel(arm) {
    var host = document.getElementById("dx-funnel");
    if (!host) return;
    var a = S.arms[arm];
    if (!a) { fail(host, "No state for arm " + arm); return; }

    var st = stagesOf(a);
    var W = host.clientWidth || 760, rowH = 30, padL = 168, padR = 96, padT = 8, padB = 30;
    var H = padT + st.length * rowH + padB;
    var maxN = Math.max.apply(null, st.map(function (s) { return s.n; })) || 1;

    host.innerHTML = "";
    var svg = d3.select(host).append("svg")
      .attr("viewBox", "0 0 " + W + " " + H)
      .attr("width", "100%").attr("height", H)
      .attr("role", "img")
      .attr("aria-label", "Funnel for " + arm);

    var g = svg.append("g");
    var x = d3.scaleLinear().domain([0, maxN]).range([0, W - padL - padR]);

    st.forEach(function (s, i) {
      var y = padT + i * rowH;
      var isDrop = s.kind === "drop";
      var col = isDrop ? C.drop : (s.kind === "src" ? C.dim : C.keep);

      g.append("text").attr("class", "dx-lab")
        .attr("x", padL - 10).attr("y", y + rowH / 2 + 4).attr("text-anchor", "end")
        .text(s.label);

      g.append("rect").attr("class", "dx-bar dx-bar-" + s.kind)
        .attr("x", padL).attr("y", y + 5)
        .attr("width", Math.max(1.5, x(s.n))).attr("height", rowH - 12)
        .attr("fill", col).attr("opacity", isDrop ? 0.55 : 0.92)
        .on("mousemove", function (ev) {
          var pct = a.source_records ? (100 * s.n / a.source_records) : null;
          showTip(ev, "<b>" + s.label + "</b><br>" + fmt(s.n) + " records" +
                      (pct !== null ? "<br>" + pct.toFixed(1) + "&nbsp;% of source" : ""));
        })
        .on("mouseleave", hideTip);

      g.append("text").attr("class", "dx-val")
        .attr("x", padL + Math.max(1.5, x(s.n)) + 8).attr("y", y + rowH / 2 + 4)
        .text(fmt(s.n) + (isDrop ? "  removed" : ""));
    });

    g.attr("data-d3-marks", st.length);

    //  The headline the funnel exists to state: how much of the source survives to items.
    var kept = a.items_attempted, src = a.source_records;
    svg.append("text").attr("class", "dx-note")
      .attr("x", padL).attr("y", H - 10)
      .text("survives to items: " + fmt(kept) + " of " + fmt(src) +
            (src ? "  (" + (100 * kept / src).toFixed(1) + " %)" : ""));

    //  Arm selector lives in the section markup; reflect the active one here.
    d3.selectAll("#dx-funnel-tabs .dx-tab").classed("is-active", function () {
      return d3.select(this).attr("data-arm") === arm;
    });
  }

  // ── B. layer coverage matrix ───────────────────────────────────────────────────────────────────
  //  THE POINT OF THE DATASET. Layers are not shared evenly: this view shows which are present in
  //  which arm, because a cross-script comparison is only defined on the layers two arms have in
  //  common. A blank cell is a layer that arm does not offer, and it is drawn as a blank, not as zero.

  function drawLayers() {
    var host = document.getElementById("dx-layers");
    if (!host) return;
    var cols = LAYER_ORDER.slice();
    ARM_ORDER.forEach(function (a) {
      Object.keys(S.arms[a].layers || {}).forEach(function (l) {
        if (cols.indexOf(l) < 0) cols.push(l);
      });
    });

    var cell = 46, padL = 92, padT = 34, padB = 52;
    var W = padL + cols.length * cell + 24, H = padT + ARM_ORDER.length * cell + padB;
    host.innerHTML = "";
    var svg = d3.select(host).append("svg")
      .attr("viewBox", "0 0 " + W + " " + H).attr("width", "100%").attr("height", H)
      .attr("role", "img").attr("aria-label", "Layer coverage by arm");

    var vals = [];
    ARM_ORDER.forEach(function (a) {
      cols.forEach(function (l) {
        var v = (S.arms[a].layers || {})[l];
        if (typeof v === "number") vals.push(v);
      });
    });
    var maxV = Math.max.apply(null, vals.concat([1]));
    var shade = d3.scaleSequential(d3.interpolateBlues).domain([0, maxV]);

    var g = svg.append("g");
    cols.forEach(function (l, j) {
      g.append("text").attr("class", "dx-colhead")
        .attr("x", padL + j * cell + cell / 2).attr("y", padT - 10).attr("text-anchor", "middle")
        .text(l);
    });

    var marks = 0;
    ARM_ORDER.forEach(function (a, i) {
      var y = padT + i * cell;
      g.append("text").attr("class", "dx-lab")
        .attr("x", padL - 10).attr("y", y + cell / 2 + 4).attr("text-anchor", "end").text(a);

      cols.forEach(function (l, j) {
        var v = (S.arms[a].layers || {})[l];
        var x = padL + j * cell;
        if (typeof v === "number") {
          g.append("rect").attr("class", "dx-cell").attr("class", "dx-cell has-value")
            .attr("x", x + 2).attr("y", y + 2).attr("width", cell - 4).attr("height", cell - 4)
            .attr("fill", shade(v)).attr("stroke", C.line).attr("stroke-width", 0.6)
            .on("mousemove", function (ev) {
              showTip(ev, "<b>" + a + "</b> \u00b7 " + l + "<br>" + fmt(v) + " items");
            }).on("mouseleave", hideTip);
          g.append("text").attr("class", "dx-cellval")
            .attr("x", x + cell / 2).attr("y", y + cell / 2 - 1).attr("text-anchor", "middle")
            .text(v >= 1000 ? (v / 1000).toFixed(1) + "k" : String(v));
          marks++;
        } else {
          //  Absent, not zero. A hatched blank so it cannot be read as a small count.
          g.append("rect").attr("class", "dx-cell is-empty")
            .attr("x", x + 2).attr("y", y + 2).attr("width", cell - 4).attr("height", cell - 4)
            .attr("fill", "url(#dx-hatch)").attr("stroke", C.line).attr("stroke-width", 0.6)
            .on("mousemove", function (ev) {
              showTip(ev, "<b>" + a + "</b> \u00b7 " + l + "<br>not offered by this arm");
            }).on("mouseleave", hideTip);
          marks++;
        }
      });
    });

    var defs = svg.append("defs");
    var pat = defs.append("pattern").attr("id", "dx-hatch")
      .attr("width", 6).attr("height", 6).attr("patternUnits", "userSpaceOnUse");
    pat.append("rect").attr("width", 6).attr("height", 6).attr("fill", "#f2f4f7");
    pat.append("path").attr("d", "M0,6 l6,-6").attr("stroke", "#d2d8e0").attr("stroke-width", 1);

    g.attr("data-d3-marks", marks);
    svg.append("text").attr("class", "dx-note")
      .attr("x", padL).attr("y", H - 16)
      .text("a hatched cell is a layer the arm does not offer \u2014 absent, not zero");
  }

  // ── C. distributional signature ────────────────────────────────────────────────────────────────
  //  The per-arm statistics a reader needs to judge whether two arms are comparable at all. Values
  //  are read from the arm records; a statistic missing for an arm is left as a gap and named, never
  //  interpolated.

  var STATS = [
    { k: "state_len",  f: "state_len",  sub: "median", label: "observed form length, median (graphemes)" },
    { k: "root_max",   f: "root_max",   sub: null,     label: "longest root (graphemes)" },
    { k: "margin_median", f: "margin_median", sub: null, label: "candidate margin, median" },
    { k: "group_rank", f: "group_rank", sub: "median", label: "homophone-group frequency rank, median" },
    { k: "group_size_median", f: "group_size_median", sub: null, label: "homophone group size, median" },
    { k: "unit_violations", f: "unit_violations", sub: null, label: "unit-consistency violations" }
  ];

  function statValue(a, spec) {
    var v = S.arms[a][spec.f];
    if (v && typeof v === "object" && spec.sub) v = v[spec.sub];
    return typeof v === "number" ? v : null;
  }

  function drawStats(statKey) {
    var host = document.getElementById("dx-stats");
    if (!host) return;
    var spec = null;
    STATS.forEach(function (s) { if (s.k === statKey) spec = s; });
    if (!spec) spec = STATS[0];

    var rows = ARM_ORDER.map(function (a) { return { arm: a, v: statValue(a, spec) }; });
    var rowH = 26, padL = 92, padR = 74, padT = 10, padB = 26;
    var W = host.clientWidth || 760, H = padT + rows.length * rowH + padB;

    host.innerHTML = "";
    var svg = d3.select(host).append("svg")
      .attr("viewBox", "0 0 " + W + " " + H).attr("width", "100%").attr("height", H)
      .attr("role", "img").attr("aria-label", spec.label);

    var present = rows.filter(function (r) { return r.v !== null; });
    var maxV = present.length ? Math.max.apply(null, present.map(function (r) { return r.v; })) : 1;
    var x = d3.scaleLinear().domain([0, maxV || 1]).range([0, W - padL - padR]);
    var g = svg.append("g");

    rows.forEach(function (r, i) {
      var y = padT + i * rowH;
      g.append("text").attr("class", "dx-lab")
        .attr("x", padL - 10).attr("y", y + rowH / 2 + 4).attr("text-anchor", "end").text(r.arm);
      if (r.v === null) {
        g.append("text").attr("class", "dx-missing")
          .attr("x", padL).attr("y", y + rowH / 2 + 4)
          .text("not reported for this arm");
        return;
      }
      g.append("rect").attr("class", "dx-bar")
        .attr("x", padL).attr("y", y + 4)
        .attr("width", Math.max(1.5, x(r.v))).attr("height", rowH - 11)
        .attr("fill", C.soft).attr("opacity", 0.9)
        .on("mousemove", function (ev) {
          showTip(ev, "<b>" + r.arm + "</b><br>" + spec.label + "<br>" + fmt(r.v));
        }).on("mouseleave", hideTip);
      g.append("text").attr("class", "dx-val")
        .attr("x", padL + Math.max(1.5, x(r.v)) + 8).attr("y", y + rowH / 2 + 4)
        .text(fmt(r.v));
    });

    g.attr("data-d3-marks", rows.length);
    svg.append("text").attr("class", "dx-note")
      .attr("x", padL).attr("y", H - 10).text(spec.label);
  }

  // ── wiring ─────────────────────────────────────────────────────────────────────────────────────

  var tabs = document.getElementById("dx-funnel-tabs");
  if (tabs) {
    tabs.innerHTML = "";
    ARM_ORDER.forEach(function (a) {
      var b = document.createElement("button");
      b.className = "dx-tab";
      b.type = "button";
      b.setAttribute("data-arm", a);
      b.textContent = a;
      b.addEventListener("click", function () { drawFunnel(a); });
      tabs.appendChild(b);
    });
    //  Default to the arm the report's main measurement used, when the state names it.
    drawFunnel(S.measurement && S.measurement._source_file
      ? (ARM_ORDER.filter(function (a) { return S.arms[a].n_items; })[0] || ARM_ORDER[0])
      : ARM_ORDER[0]);
  }

  var sel = document.getElementById("dx-stat-select");
  if (sel) {
    sel.innerHTML = "";
    STATS.forEach(function (s) {
      var o = document.createElement("option");
      o.value = s.k; o.textContent = s.label;
      sel.appendChild(o);
    });
    sel.addEventListener("change", function () { drawStats(sel.value); });
  }

  drawLayers();
  drawStats(sel ? sel.value : STATS[0].k);

  //  Redraw on resize: the SVGs use a viewBox, so only the bar scales need recomputing.
  var tmr = null;
  window.addEventListener("resize", function () {
    clearTimeout(tmr);
    tmr = setTimeout(function () {
      var host = document.getElementById("dx-funnel");
      var act = host && host.querySelector(".dx-tab.is-active");
      drawFunnel(act ? act.getAttribute("data-arm") : ARM_ORDER[0]);
      drawStats(sel ? sel.value : STATS[0].k);
    }, 160);
  });
})();
